# Comparision Operator : 
'''
comparision operator is used to compare 2 values and return a boolean result either True or False.
'''

num1 = int(input("Enter first input number : "))
num2 = int(input("Enter second input number : "))
print("Equals to  ==",num1 == num2)
print("Not Equals To !=",num1 != num2)
print("Greater Than >",num1 > num2)
print("Greater Than Equals To >=",num1 >= num2)
print("Less Than >",num1 < num2)
print("Less Than Equals To <=",num1 <= num2)
