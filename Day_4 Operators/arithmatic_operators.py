# Arithmatic Operator
'''
Arithmatic operator are used when we want to work with some mathmatical calculations like addition , subtraction , division , multiplication , floor division , modulus and exponent.
''' 

num1 = int(input("Enter first input number : "))
num2 = int(input("Enter second input number : "))
print("Addition =",num1 + num2)
print("Subtraction =",num1 - num2)
print("Multiplication =",num1 * num2)
print("Division =",num1 / num2)
print("Floor Division =",num1 // num2)
print("Modulus =",num1 % num2)
print("Exponent =",num1 ** num2)