# Set 
'''
Set is a built in data structure which is used to store collection of unique elements seperated by commas inside curly brackets.

1.Set is mutable in nature but it can store only immutable elements like string , numbers , tuple.
2.Set is unordered collection of data structure so indexing and slicing is not possible inside set.
3.Set does not allow duplicate values.
4.Set store only unique elements.
5.Set support some mathematical operations like union , intersection , difference and symetric-difference
'''


# To create an empty set : 
'''
s = set()
print(s)
'''


# Create a set in python :
s = {10,20,30,40}
print(s)
